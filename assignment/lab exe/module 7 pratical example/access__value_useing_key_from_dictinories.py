# Example of accessing values in a dictionary using keys

# Creating a dictionary
my_dict = {
    "name": "Alice",
    "age": 25,
    "city": "New York",
    "course": "Python"
}

# Accessing values using keys
print("Name:", my_dict["name"])
print("Age:", my_dict["age"])
print("City:", my_dict["city"])
print("Course:", my_dict["course"])
